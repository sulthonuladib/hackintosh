#!/usr/bin/env python3
"""Print a Markdown inventory of an OpenCore config.plist.

    scripts/config-inventory.py devices/<machine>/efi/config.plist > devices/<machine>/efi/inventory.md

Read-only; use it on the sanitized snapshot in this repo, not on a raw config from a stick.
"""
import plistlib
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], "rb") as f:
        cfg = plistlib.load(f)

    acpi = cfg.get("ACPI", {})
    kernel = cfg.get("Kernel", {})
    uefi = cfg.get("UEFI", {})
    misc = cfg.get("Misc", {})
    boot = cfg.get("Booter", {})
    platform = cfg.get("PlatformInfo", {})
    generic = platform.get("Generic", {})
    nvram = cfg.get("NVRAM", {}).get("Add", {}).get("7C436110-AB2A-4BBB-A880-FE41995C9F82", {})
    apple = "7C436110-AB2A-4BBB-A880-FE41995C9F82"

    out = []
    add = out.append
    add("# Config inventory")
    add("")
    add("Generated by `scripts/config-inventory.py` from `config.plist`. Do not edit by hand.")
    add("")

    add("## Platform")
    add("")
    add("| | |")
    add("|---|---|")
    add("| SMBIOS | `%s` |" % generic.get("SystemProductName", "?"))
    add("| ProcessorType | `%s` |" % generic.get("ProcessorType", "?"))
    add("| SecureBootModel | `%s` |" % misc.get("Security", {}).get("SecureBootModel"))
    add("| Vault | `%s` |" % misc.get("Security", {}).get("Vault"))
    add("| ScanPolicy | `%s` |" % misc.get("Security", {}).get("ScanPolicy"))
    emulate = kernel.get("Emulate", {})
    if emulate.get("Cpuid1Data"):
        data = emulate["Cpuid1Data"]
        add("| Emulated CPUID1 | `0x%s` |" % "".join("%02X" % b for b in data[4::-1]))
    add("| boot-args | `%s` |" % nvram.get("boot-args", ""))
    add("| csr-active-config | `%s` |" % (nvram.get("csr-active-config", b"").hex()))
    add("")

    add("## ACPI (%d)" % len(acpi.get("Add", [])))
    add("")
    for item in acpi.get("Add", []):
        state = "" if item.get("Enabled", True) else " *(disabled)*"
        add("- `%s`%s" % (item.get("Path"), state))
    add("")

    kexts = [k for k in kernel.get("Add", []) if k.get("BundlePath", "").count("/") == 0]
    plugins = [k for k in kernel.get("Add", []) if k.get("BundlePath", "").count("/") > 0]
    add("## Kexts (%d entries: %d kexts, %d plugins)" % (len(kexts) + len(plugins), len(kexts), len(plugins)))
    add("")
    add("| Kext | MinKernel | MaxKernel | State |")
    add("|---|---|---|---|")
    for k in kexts + plugins:
        state = "on" if k.get("Enabled", True) else "**off**"
        add("| `%s` | %s | %s | %s |" % (k.get("BundlePath"), k.get("MinKernel") or "—", k.get("MaxKernel") or "—", state))
    add("")

    add("## Drivers (%d)" % len(uefi.get("Drivers", [])))
    add("")
    for d in uefi.get("Drivers", []):
        state = "" if d.get("Enabled", True) else " *(disabled)*"
        add("- `%s`%s" % (d.get("Path"), state))
    add("")

    add("## Tools (%d)" % len(misc.get("Tools", [])))
    add("")
    for t in misc.get("Tools", []):
        state = "" if t.get("Enabled", True) else " *(disabled)*"
        add("- `%s`%s" % (t.get("Path"), state))
    add("")

    entries = misc.get("Entries", [])
    add("## Boot entries (%d)" % len(entries))
    add("")
    for e in entries:
        add("- `%s` → `%s`" % (e.get("Name"), e.get("Path")))
    add("")

    add("## Quirks enabled")
    add("")
    for name, section in (("Booter", boot.get("Quirks", {})), ("Kernel", kernel.get("Quirks", {})), ("UEFI", uefi.get("Quirks", {}))):
        enabled = [k for k, v in sorted(section.items()) if v is True]
        add("- **%s**: %s" % (name, ", ".join("`%s`" % k for k in enabled) or "none"))
    add("")

    props = cfg.get("DeviceProperties", {}).get("Add", {})
    add("## DeviceProperties (%d devices)" % len(props))
    add("")
    for path, values in props.items():
        add("### `%s`" % path)
        add("")
        for key, value in values.items():
            if isinstance(value, bytes):
                value = value.hex()
            add("- `%s` = `%s`" % (key, value))
        add("")

    add("## NVRAM Add (%s)" % apple)
    add("")
    for key, value in nvram.items():
        if isinstance(value, bytes):
            value = value.hex()
        add("- `%s` = `%s`" % (key, value))
    add("")

    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
